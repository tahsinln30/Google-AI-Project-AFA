// Generates cohesive falling avatar/silhouette if a name doesn't exist
export function getPlayerImage(name: string, isReserve = false): string {
  if (!name) return "https://images.unsplash.com/photo-1508098682722-e99c43a406b2?q=80&w=300&auto=format&fit=crop";

  const cleanName = name.normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim().toLowerCase();
  const imagesObj = isReserve ? RESERVE_IMAGES : PLAYER_IMAGES;
  
  const matchedKey = Object.keys(imagesObj).find(k => {
    const cleanKey = k.normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim().toLowerCase();
    return cleanKey === cleanName;
  });

  if (matchedKey) {
    return imagesObj[matchedKey];
  }

  const altImagesObj = isReserve ? PLAYER_IMAGES : RESERVE_IMAGES;
  const matchedAltKey = Object.keys(altImagesObj).find(k => {
    const cleanKey = k.normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim().toLowerCase();
    return cleanKey === cleanName;
  });

  if (matchedAltKey) {
    return altImagesObj[matchedAltKey];
  }

  return "https://images.unsplash.com/photo-1508098682722-e99c43a406b2?q=80&w=300&auto=format&fit=crop";
}
